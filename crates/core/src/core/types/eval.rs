//! `Evaluator`, the evaluator, and the runtime budget constants.

use rustc_hash::{FxHashMap, FxHashSet};
use std::collections::HashMap;
use std::sync::Arc;

use crate::core::errors::MizuError;
use crate::parser::logic::{
    BinOp, Expr, ExprArena, MizuFunction, apply_binop, check_type, type_name,
};

use super::interner::{FrozenInterner, Symbol};
use super::value::Value;

/// Maximum byte length of a single interpolated text run.
///
/// Interpolation is the one place a value crosses out of the budgeted
/// evaluator and into the renderer: [`Evaluator::interpolate_into_with_overlay`]
/// runs during layout/paint, not during `evaluate`, so `max_instructions`
/// never applies to it. Without a ceiling, one `text "{data}"` node bound to a
/// network response (bounded only by the 32 MiB transfer cap, and a single
/// JSON node, so `MAX_JSON_NODES` never fires) hands tens of megabytes to
/// parley's shaper on the UI thread, on every layout pass — an unmetered
/// main-thread stall reachable from a two-line document.
///
/// 64 KiB is far beyond any text a person reads on one node while keeping the
/// worst case per node in the sub-millisecond range. Exceeding it is an error
/// rather than a silent truncation: a caller must not be able to mistake a
/// clipped prefix of attacker-controlled data for the whole value (the same
/// reject-don't-sanitize rule `from_json_slice` applies to over-deep input).
pub const MAX_INTERPOLATED_BYTES: usize = 64 * 1024;

/// Maximum recursion depth for [`Evaluator::evaluate`].
///
/// Prevents a native stack overflow on deeply-nested ASTs (e.g. crafted by
/// constructing an AST directly, or generated by an adversarial parser input
/// that slipped through [`crate::parser::logic::MAX_PARSE_DEPTH`]).
/// 256 is well below the native stack limit (~8 MB / ~64 B per frame ≈ thousands
/// of levels) while being unreachable by any legitimate Mizu expression.
///
/// This is also the floor for [`MAX_JSON_DEPTH`]: a [`Value`] built up to
/// this depth by the evaluator must remain re-readable from encrypted
/// storage on the next load.
pub const MAX_EVAL_DEPTH: u32 = 256;

/// Data-oriented flat state machine with a contiguous local variable stack and O(1) global lookup.
#[derive(Debug, Clone)]
pub struct Evaluator {
    /// Global variable store keyed by Symbol.
    /// Uses FxHashMap (rustc-hash) instead of the SipHash default because Symbol is a u32
    /// sequential integer — DoS-resistance on integer keys is unnecessary overhead.
    pub global_store: FxHashMap<Symbol, Value>,
    /// Contiguous stack of local-binding values, indexed by `local_index`.
    pub local_stack: Vec<Value>,
    /// Symbol bound at each position of `local_stack` (parallel array).
    pub local_symbols: Vec<Symbol>,
    /// O(1) reverse index: Symbol → ordered list of indices into `local_stack` where that
    /// symbol is bound (earliest first, latest last).  Kept in sync with `local_stack` /
    /// `local_symbols` by `push_local`, `pop_local`, and `truncate_locals`.
    ///
    /// Lookup rule: the *last* index in the list is the innermost (shadow-winning) binding.
    /// A binding is in scope when its index ≥ the current frame_pointer.
    pub local_index: FxHashMap<Symbol, Vec<usize>>,
    /// Running count of evaluation steps since the last reset.
    pub instruction_count: u64,
    /// Maximum allowed instructions before evaluation is aborted.
    pub max_instructions: u64,
    /// Current `evaluate` recursion depth; see [`MAX_EVAL_DEPTH`].
    pub eval_depth: u32,
    /// Capability actions (network calls, storage writes, navigation, …)
    /// queued by the current action/expression evaluation, drained by the
    /// caller after execution completes.
    pub accumulated_actions: Vec<crate::messages::RuntimeAction>,
    /// `(symbol, previous_value)` pairs recorded by [`Self::set_global`],
    /// enabling rollback on error and diffing to find mutated variables.
    pub undo_log: Vec<(Symbol, Value)>,
    /// Set of symbols that are computed (derived) variables.
    ///
    /// Assignment to any symbol in this set is rejected by [`execute_action`] at
    /// runtime.  Populated by the logic worker on each document reload.
    pub computed_var_syms: FxHashSet<Symbol>,
}

impl Default for Evaluator {
    fn default() -> Self {
        Self::new(20_000)
    }
}

impl Evaluator {
    /// Creates an empty state machine with pre-allocated capacity for
    /// globals, locals, and the undo log.
    pub fn new(max_instructions: u64) -> Self {
        Self {
            global_store: FxHashMap::with_capacity_and_hasher(128, Default::default()),
            local_stack: Vec::with_capacity(128),
            local_symbols: Vec::with_capacity(128),
            local_index: FxHashMap::default(),
            instruction_count: 0,
            max_instructions,
            eval_depth: 0,
            accumulated_actions: Vec::new(),
            undo_log: Vec::with_capacity(64),
            computed_var_syms: FxHashSet::default(),
        }
    }

    /// Pushes a new local binding of `sym` to `val` onto the local stack.
    pub fn push_local(&mut self, sym: Symbol, val: Value) {
        let idx = self.local_stack.len();
        self.local_stack.push(val);
        self.local_symbols.push(sym);
        self.local_index.entry(sym).or_default().push(idx);
    }

    /// Pops the most recently pushed local binding, if any.
    pub fn pop_local(&mut self) {
        if let Some(sym) = self.local_symbols.pop() {
            self.local_stack.pop();
            if let Some(v) = self.local_index.get_mut(&sym) {
                v.pop();
                if v.is_empty() {
                    self.local_index.remove(&sym);
                }
            }
        }
    }

    /// Truncate the local stack to `new_len` entries, removing index entries for every
    /// binding at positions ≥ `new_len`.  Used at function-call exit to discard the
    /// call frame's argument bindings.
    pub fn truncate_locals(&mut self, new_len: usize) {
        for i in (new_len..self.local_symbols.len()).rev() {
            let sym = self.local_symbols[i];
            if let Some(v) = self.local_index.get_mut(&sym) {
                v.pop();
                if v.is_empty() {
                    self.local_index.remove(&sym);
                }
            }
        }
        self.local_stack.truncate(new_len);
        self.local_symbols.truncate(new_len);
    }

    /// Assigns `val` to the global binding of `sym`, recording the previous
    /// value in `undo_log` for rollback/diffing.
    pub fn set_global(&mut self, sym: Symbol, val: Value) {
        let old_val = self.global_store.insert(sym, val).unwrap_or(Value::Null);
        self.undo_log.push((sym, old_val));
    }

    /// Returns the global binding of `sym`, or [`Value::Null`] if unset.
    pub fn get_global(&self, sym: Symbol) -> &Value {
        static NULL: std::sync::OnceLock<Value> = std::sync::OnceLock::new();
        self.global_store
            .get(&sym)
            .unwrap_or(NULL.get_or_init(|| Value::Null))
    }

    /// Resolves a local symbol value in O(1) average time using the reverse index.
    ///
    /// Shadowing semantics: the innermost (most recently pushed) binding whose stack
    /// index is ≥ `frame_pointer` wins.  Bindings pushed before the current function
    /// call frame have indices < `frame_pointer` and are invisible to the callee.
    pub fn get_local(&self, sym: Symbol, frame_pointer: usize) -> Option<&Value> {
        if let Some(indices) = self.local_index.get(&sym)
            && let Some(&idx) = indices.last()
            && idx >= frame_pointer
        {
            return Some(&self.local_stack[idx]);
        }
        None
    }

    /// Looks up `name` in `interner`, then resolves the resulting symbol as a
    /// local (if in scope) or a non-null global.  Returns `None` if `name` is
    /// unknown or bound to nothing.
    pub fn get_value_by_name(&self, name: &str, interner: &FrozenInterner) -> Option<&Value> {
        if let Some(sym) = interner.get(name) {
            if let Some(val) = self.get_local(sym, 0) {
                return Some(val);
            }
            if let Some(val) = self.global_store.get(&sym)
                && !matches!(val, Value::Null)
            {
                return Some(val);
            }
        }
        None
    }

    /// Renders raw text formatting interpolations directly into a pre-allocated buffer.
    #[inline]
    pub fn interpolate_into(
        &self,
        raw_text: &str,
        interner: &FrozenInterner,
        buffer: &mut String,
    ) -> Result<(), MizuError> {
        self.interpolate_into_with_overlay(raw_text, interner, None, buffer)
    }

    /// Core interpolation engine. Uses lean, manual string slicing with `str::find`
    /// for fast bulk memory scanning.
    pub(super) fn interpolate_into_with_overlay(
        &self,
        raw_text: &str,
        interner: &FrozenInterner,
        overlay: Option<&HashMap<String, Value>>,
        buffer: &mut String,
    ) -> Result<(), MizuError> {
        use std::fmt::Write;
        // Every write below goes through this cap, so no single value — and
        // no accumulation of values — can hand the renderer an unbounded run.
        // See `MAX_INTERPOLATED_BYTES`. The overflow is rejected at the point
        // of the offending write, before the bytes are copied, so the peak
        // allocation stays bounded even when the source value is enormous.
        let buffer = &mut CappedBuffer {
            buf: buffer,
            cap: MAX_INTERPOLATED_BYTES,
        };
        let mut rest = raw_text;

        while let Some(idx) = rest.find(|c| c == '{' || c == '\\') {
            buffer.push_str(&rest[..idx])?;

            let c = rest.as_bytes()[idx];
            if c == b'\\' {
                rest = &rest[idx + 1..];
                if let Some(next_char) = rest.chars().next() {
                    if next_char == '\\' || next_char == '{' || next_char == '}' {
                        buffer.push(next_char)?;
                        rest = &rest[next_char.len_utf8()..];
                    } else {
                        buffer.push('\\')?;
                    }
                } else {
                    buffer.push('\\')?;
                }
            } else if c == b'{' {
                rest = &rest[idx + 1..];
                // Check for double curly brace `{{` which could mean escaped brace, but
                // Mizu format actually uses `\{` for escaping. For now we just look for `}`.
                if let Some(end_idx) = rest.find('}') {
                    let var_name = &rest[..end_idx];

                    if var_name.contains('.') {
                        const MAX_RECORD_DEPTH: usize = 64;
                        let mut parts = var_name.splitn(MAX_RECORD_DEPTH, '.');
                        let root = parts.next().unwrap_or("");

                        let handled = match overlay.and_then(|map| map.get(root)) {
                            Some(root_val) => match resolve_dot_path(root_val, parts.clone()) {
                                Some(leaf) => {
                                    write!(buffer, "{}", leaf).map_err(interpolation_overflow)?;
                                    true
                                }
                                None => false,
                            },
                            None => false,
                        };

                        if !handled {
                            match self.get_value_by_name(root, interner) {
                                None => {
                                    write!(buffer, "{{{}}}", var_name)
                                        .map_err(interpolation_overflow)?;
                                }
                                Some(root_val) => match resolve_dot_path(root_val, parts) {
                                    Some(leaf) => {
                                        write!(buffer, "{}", leaf)
                                            .map_err(interpolation_overflow)?;
                                    }
                                    None => {
                                        tracing::warn!(
                                            "interpolation: path `{}` could not be resolved",
                                            var_name
                                        );
                                        write!(buffer, "{{{}}}", var_name)
                                            .map_err(interpolation_overflow)?;
                                    }
                                },
                            }
                        }
                    } else {
                        match overlay.and_then(|map| map.get(var_name)) {
                            Some(val) => {
                                write!(buffer, "{}", val).map_err(interpolation_overflow)?;
                            }
                            None => {
                                if let Some(val) = self.get_value_by_name(var_name, interner) {
                                    write!(buffer, "{}", val).map_err(interpolation_overflow)?;
                                } else {
                                    write!(buffer, "{{{}}}", var_name)
                                        .map_err(interpolation_overflow)?;
                                    tracing::warn!("Variable binding missing: {}", var_name);
                                }
                            }
                        }
                    }
                    rest = &rest[end_idx + 1..];
                } else {
                    buffer.push('{')?;
                }
            }
        }
        buffer.push_str(rest)?;
        Ok(())
    }

    /// Evaluates a Mizu expression to a concrete Value.
    ///
    /// Budget enforcement is pure-integer: each recursive call increments
    /// `self.instruction_count` and the method returns `Err(MizuError::Timeout)`
    /// once the count exceeds [`MAX_INSTRUCTIONS`].  No hardware clock is read
    /// inside the hot loop — callers must reset `instruction_count` to `0`
    /// before each top-level invocation.
    ///
    /// `eval_depth` guards against native stack overflow on deeply-nested ASTs.
    /// It is incremented on entry and decremented before every return so it is
    /// always consistent; callers do not need to reset it.
    pub fn evaluate(
        &mut self,
        expr: &Expr,
        frame_pointer: usize,
        functions: &FxHashMap<Symbol, MizuFunction>,
        interner: &FrozenInterner,
        arena: &ExprArena,
    ) -> Result<Value, MizuError> {
        self.instruction_count += 1;
        if self.instruction_count > self.max_instructions {
            return Err(MizuError::Timeout);
        }
        self.eval_depth += 1;
        if self.eval_depth > MAX_EVAL_DEPTH {
            self.eval_depth -= 1;
            return Err(MizuError::ExecutionError(
                "evaluation nesting too deep (max 256 levels)".to_owned(),
            ));
        }
        let result = self.evaluate_impl(expr, frame_pointer, functions, interner, arena);
        self.eval_depth -= 1;
        result
    }

    fn evaluate_impl(
        &mut self,
        expr: &Expr,
        frame_pointer: usize,
        functions: &FxHashMap<Symbol, MizuFunction>,
        interner: &FrozenInterner,
        arena: &ExprArena,
    ) -> Result<Value, MizuError> {
        match expr {
            Expr::Literal(v) => Ok(v.clone()),
            Expr::Variable(sym) => {
                if let Some(val) = self.get_local(*sym, frame_pointer) {
                    Ok(val.clone())
                } else {
                    let val = self.get_global(*sym);
                    if !matches!(val, Value::Null) {
                        Ok(val.clone())
                    } else {
                        let name = interner.resolve(*sym).unwrap_or("<unknown>").to_owned();
                        Err(MizuError::VariableNotFound(name))
                    }
                }
            }
            Expr::BinaryOp { left, op, right } => {
                let lv = self.evaluate(&arena[*left], frame_pointer, functions, interner, arena)?;
                let rv =
                    self.evaluate(&arena[*right], frame_pointer, functions, interner, arena)?;
                apply_binop(
                    op,
                    lv,
                    rv,
                    &mut self.instruction_count,
                    self.max_instructions,
                )
            }
            Expr::FunctionCall {
                name: sym,
                args_start,
                args_len,
            } => {
                let args = arena.args(*args_start, *args_len);
                let resolved_name = interner.resolve(*sym).unwrap_or("<unknown>");
                match resolved_name {
                    "copy_to_clipboard" => {
                        if args.len() != 1 {
                            return Err(MizuError::ExecutionError(
                                "copy_to_clipboard expects 1 argument".to_string(),
                            ));
                        }
                        let val = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let node_id = match val {
                            Value::String(ref s) => s.to_string(),
                            _ => {
                                return Err(MizuError::ExecutionError(
                                    "copy_to_clipboard argument must be a node id string"
                                        .to_string(),
                                ));
                            }
                        };
                        self.accumulated_actions
                            .push(crate::messages::RuntimeAction::CopyToClipboard { node_id });
                        return Ok(Value::Bool(true));
                    }
                    "get_system_time" => {
                        // arg[0] must be a bare variable identifier (Expr::Variable),
                        // never evaluated — mirrors `download`'s alias argument.
                        //
                        // Before this restriction, the argument was evaluated as an
                        // arbitrary expression to a string used to *look up* the
                        // write target at runtime, making get_system_time the only
                        // construct in the language whose assignment target was
                        // chosen dynamically rather than fixed at parse time. That
                        // broke the static flow checker's core assumption (every
                        // write target is a known Symbol, `parser::flow.rs`) and put
                        // the write out of reach of taint analysis entirely: a
                        // target string derived from `$form`/a network response
                        // could redirect the write to any variable with no static
                        // check able to see it. Requiring a bare identifier here
                        // fixes the target at parse time, so this is now analyzable
                        // exactly like any other assignment.
                        let target_variable = match args {
                            [id] if matches!(&arena[*id], Expr::Variable(_)) => {
                                let Expr::Variable(sym) = &arena[*id] else {
                                    unreachable!()
                                };
                                *sym
                            }
                            _ => {
                                return Err(MizuError::ExecutionError(
                                    "get_system_time expects a single bare variable \
                                     identifier, e.g. get_system_time(my_var)"
                                        .to_string(),
                                ));
                            }
                        };
                        if self.computed_var_syms.contains(&target_variable) {
                            return Err(MizuError::ExecutionError(
                                "get_system_time cannot target a computed variable".to_string(),
                            ));
                        }
                        self.accumulated_actions.push(
                            crate::messages::RuntimeAction::GetSystemTime { target_variable },
                        );
                        return Ok(Value::Bool(true));
                    }
                    "store_local" => {
                        if args.len() != 2 {
                            return Err(MizuError::ExecutionError(
                                "store_local expects 2 arguments: (key, value)".to_string(),
                            ));
                        }
                        let key_val = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let key_str = match key_val {
                            Value::String(ref s) => s.to_string(),
                            _ => {
                                return Err(MizuError::ExecutionError(
                                    "store_local key must be a string".to_string(),
                                ));
                            }
                        };
                        let value = self.evaluate(
                            &arena[args[1]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        self.accumulated_actions
                            .push(crate::messages::RuntimeAction::StoreLocal {
                                key: key_str,
                                value,
                            });
                        return Ok(Value::Bool(true));
                    }
                    "filter" if args.len() == 4 => {
                        let list_val = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let field_val = self.evaluate(
                            &arena[args[1]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        // args[2] is always Expr::Literal(Value::String(op)) — the
                        // parser desugars filter's 3-argument surface form to
                        // `op = "eq"` and only ever accepts one of FILTER_OPS as a
                        // bare keyword for the 4-argument form (parser/logic/parse.rs).
                        // Evaluating it here is a formality, never a variable lookup.
                        let op_val = self.evaluate(
                            &arena[args[2]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let target = self.evaluate(
                            &arena[args[3]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let list = match list_val {
                            Value::List(ref l) => l.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("list".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        let field = match field_val {
                            Value::String(ref s) => s.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        let op = match op_val {
                            Value::String(ref s) => s.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        // Charge the instruction budget before the native iteration to prevent
                        // large lists from bypassing MAX_INSTRUCTIONS via unmetered CPU work.
                        self.instruction_count =
                            self.instruction_count.saturating_add(list.len() as u64);
                        // `contains` does an O(field length) substring scan per item on
                        // top of the flat per-item charge above — pre-charge that too,
                        // mirroring the standalone `contains` builtin's own charge.
                        if op.as_ref() == "contains" {
                            let extra: u64 = list
                                .iter()
                                .filter_map(|item| {
                                    item.get_field(
                                        crate::core::types::hash_field(field.as_ref()),
                                        field.as_ref(),
                                    )
                                })
                                .filter_map(|v| match v {
                                    Value::String(s) => Some(s.len() as u64),
                                    _ => None,
                                })
                                .sum();
                            self.instruction_count = self.instruction_count.saturating_add(extra);
                        }
                        if self.instruction_count > self.max_instructions {
                            return Err(MizuError::Timeout);
                        }
                        let binop = match op.as_ref() {
                            "eq" => Some(BinOp::Eq),
                            "ne" => Some(BinOp::Ne),
                            "lt" => Some(BinOp::Lt),
                            "le" => Some(BinOp::Le),
                            "gt" => Some(BinOp::Gt),
                            "ge" => Some(BinOp::Ge),
                            "contains" => None,
                            other => {
                                return Err(MizuError::ExecutionError(format!(
                                    "filter: unknown operator `{other}` — expected one of \
                                     eq, ne, lt, le, gt, ge, contains"
                                )));
                            }
                        };
                        let mut ic = self.instruction_count;
                        let mut filtered = Vec::new();
                        for item in list.iter() {
                            if let Some(field_v) = item.get_field(
                                crate::core::types::hash_field(field.as_ref()),
                                field.as_ref(),
                            ) {
                                let include = match &binop {
                                    Some(op) => {
                                        match apply_binop(
                                            op,
                                            field_v.clone(),
                                            target.clone(),
                                            &mut ic,
                                            self.max_instructions,
                                        ) {
                                            Ok(Value::Bool(b)) => b,
                                            Ok(_) => false,
                                            Err(MizuError::TypeError { .. }) => false,
                                            Err(e) => return Err(e),
                                        }
                                    }
                                    None => match (field_v, &target) {
                                        (Value::String(h), Value::String(n)) => {
                                            h.contains(n.as_ref())
                                        }
                                        _ => false,
                                    },
                                };
                                if include {
                                    filtered.push(item.clone());
                                }
                            }
                        }
                        self.instruction_count = ic;
                        return Ok(Value::List(Arc::new(filtered)));
                    }
                    "count" if args.len() == 3 => {
                        let list_val = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let field_val = self.evaluate(
                            &arena[args[1]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let target = self.evaluate(
                            &arena[args[2]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let list = match list_val {
                            Value::List(ref l) => l.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("list".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        self.instruction_count =
                            self.instruction_count.saturating_add(list.len() as u64);
                        if self.instruction_count > self.max_instructions {
                            return Err(MizuError::Timeout);
                        }
                        let field = match field_val {
                            Value::String(ref s) => s.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        // Hashed once, not once per element: the field name is
                        // fixed for the whole pass.
                        let field_hash = crate::core::types::hash_field(field.as_ref());
                        let mut n: i64 = 0;
                        for item in list.iter() {
                            if let Some(v) = item.get_field(field_hash, field.as_ref())
                                && v.budget_eq(
                                    &target,
                                    &mut self.instruction_count,
                                    self.max_instructions,
                                )?
                            {
                                n += 1;
                            }
                        }
                        // An element count is a true integer, not a fixed-point
                        // quantity: `Value::Decimal(n)` would have meant
                        // `n / DECIMAL_SCALE`, i.e. `count(...)` reporting
                        // `0.00000003` for three matches.
                        return Ok(Value::Int(n));
                    }
                    "download" if args.len() == 1 => {
                        // arg[0] must be a bare alias identifier (Expr::Variable);
                        // aliases are not runtime variables and cannot be store-looked-up.
                        let alias_sym = match &arena[args[0]] {
                            Expr::Variable(sym) => *sym,
                            _ => return Err(MizuError::ExecutionError(
                                "download: alias must be a bare identifier, e.g. download(backup)"
                                    .to_string(),
                            )),
                        };
                        self.accumulated_actions.push(
                            crate::messages::RuntimeAction::DownloadAlias {
                                endpoint_symbol: alias_sym.0,
                            },
                        );
                        return Ok(Value::Null);
                    }
                    "sort" if args.len() == 3 => {
                        let list_val = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let field_val = self.evaluate(
                            &arena[args[1]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        // args[2] is always Expr::Literal(Value::String("asc"|"desc"))
                        // — the parser accepts nothing else in this position
                        // (parser/logic/parse.rs's parse_sort_call_args), so this is
                        // never a variable lookup and can never be shadowed by an
                        // in-scope variable literally named `asc`/`desc`.
                        let direction_val = self.evaluate(
                            &arena[args[2]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let list = match list_val {
                            Value::List(ref l) => l.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("list".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        let n = list.len();
                        let log2_n = if n > 0 {
                            usize::BITS - n.leading_zeros()
                        } else {
                            0
                        };
                        let sorting_cost = (n as u64).saturating_mul(log2_n as u64);
                        self.instruction_count =
                            self.instruction_count.saturating_add(sorting_cost);
                        if self.instruction_count > self.max_instructions {
                            return Err(MizuError::Timeout);
                        }
                        let field = match field_val {
                            Value::String(ref s) => s.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        let direction = match direction_val {
                            Value::String(ref s) => s.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        if direction.as_ref() != "asc" && direction.as_ref() != "desc" {
                            return Err(MizuError::ExecutionError(format!(
                                "sort: direction must be `asc` or `desc`, got `{direction}`"
                            )));
                        }
                        let items: Vec<Value> = (*list).clone();
                        let mut paired = Vec::with_capacity(items.len());
                        // Hashed once for the whole pass, not once per element.
                        let field_hash = crate::core::types::hash_field(field.as_ref());
                        for item in items.into_iter() {
                            let key = item.get_field(field_hash, field.as_ref()).cloned();
                            match key {
                                Some(
                                    Value::Null
                                    | Value::Bool(_)
                                    | Value::Int(_)
                                    | Value::Decimal(_)
                                    | Value::String(_),
                                )
                                | None => {}
                                _ => {
                                    return Err(MizuError::ExecutionError(
                                        "sort: cannot sort on complex nested fields (List/Record)"
                                            .to_string(),
                                    ));
                                }
                            }
                            paired.push((key, item));
                        }
                        paired.sort_by(|(ka, _), (kb, _)| {
                            let ord = compare_values(ka.as_ref(), kb.as_ref());
                            if direction.as_ref() == "desc" {
                                ord.reverse()
                            } else {
                                ord
                            }
                        });
                        let sorted_items = paired.into_iter().map(|(_, v)| v).collect();
                        return Ok(Value::List(Arc::new(sorted_items)));
                    }
                    "length" if args.len() == 1 => {
                        let value = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let n = match value {
                            // O(1): Arc<Vec<Value>>'s length is already tracked.
                            Value::List(ref l) => l.len() as i64,
                            // O(n): char count, not byte count — this is a
                            // user-facing text length for a document-rendering
                            // language, not a security byte-budget (those are
                            // separate, e.g. INPUT_MAX_BYTES), so counting
                            // Unicode scalar values is the correct choice; byte
                            // length would misreport for any multi-byte text.
                            //
                            // The byte length is an O(1) upper bound on the char
                            // count (a UTF-8 string can never have more chars
                            // than bytes), so it's charged and budget-checked
                            // *before* the O(n) `chars().count()` scan runs —
                            // otherwise a huge string (e.g. a large network
                            // response bound to a variable) would pay its full
                            // scan cost before Timeout could ever fire, letting
                            // a single length() call do MAX_INSTRUCTIONS-times
                            // more work than the budget allows.
                            Value::String(ref s) => {
                                let max_possible_chars = s.len() as u64;
                                if self.instruction_count.saturating_add(max_possible_chars)
                                    > self.max_instructions
                                {
                                    return Err(MizuError::Timeout);
                                }
                                let char_count = s.chars().count() as u64;
                                self.instruction_count =
                                    self.instruction_count.saturating_add(char_count);
                                char_count as i64
                            }
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("list or string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        // A length is a true integer — see `count` above.
                        return Ok(Value::Int(n));
                    }
                    "to_string" if args.len() == 1 => {
                        let value = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        // Numbers and bools only: reuses Value's own Display
                        // impl (which already handles DECIMAL_SCALE fixed-point
                        // formatting correctly) rather than reimplementing that
                        // logic. Anything else is a TypeError rather than
                        // silently stringifying — a list/record has no single
                        // canonical textual form, and guessing one invites
                        // confusing output over a clear rejection.
                        match &value {
                            Value::Int(_) | Value::Decimal(_) | Value::Bool(_) => {
                                return Ok(Value::String(Arc::from(value.to_string())));
                            }
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("num or bool".to_string()),
                                    found: type_name(other),
                                });
                            }
                        }
                    }
                    "contains" if args.len() == 2 => {
                        let haystack_val = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let needle_val = self.evaluate(
                            &arena[args[1]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let haystack = match haystack_val {
                            Value::String(ref s) => s.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        let needle = match needle_val {
                            Value::String(ref s) => s.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        // Charge the scan cost before doing the work — mirrors
                        // the `+` concatenation charge (same discipline: an
                        // O(n) native operation must pre-charge its size).
                        self.instruction_count =
                            self.instruction_count.saturating_add(haystack.len() as u64);
                        if self.instruction_count > self.max_instructions {
                            return Err(MizuError::Timeout);
                        }
                        return Ok(Value::Bool(haystack.contains(needle.as_ref())));
                    }
                    "has_field" if args.len() == 2 => {
                        let record_val = self.evaluate(
                            &arena[args[0]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        let name_val = self.evaluate(
                            &arena[args[1]],
                            frame_pointer,
                            functions,
                            interner,
                            arena,
                        )?;
                        if !matches!(record_val, Value::Record(_)) {
                            return Err(MizuError::TypeError {
                                expected: Box::new("record".to_string()),
                                found: type_name(&record_val),
                            });
                        }
                        let name = match name_val {
                            Value::String(ref s) => s.clone(),
                            other => {
                                return Err(MizuError::TypeError {
                                    expected: Box::new("string".to_string()),
                                    found: type_name(&other),
                                });
                            }
                        };
                        // Additive predicate only — does not relax
                        // Expr::FieldAccess's existing strict-fail-on-missing
                        // behavior; this is for callers who need to branch on
                        // optional/variable-shaped network data before ever
                        // accessing the field, not a replacement for it.
                        let present = record_val
                            .get_field(crate::core::types::hash_field(name.as_ref()), name.as_ref())
                            .is_some();
                        return Ok(Value::Bool(present));
                    }
                    _ => {}
                }

                let func = functions.get(sym).ok_or_else(|| {
                    MizuError::ParseError(format!("call to undefined function `{resolved_name}`"))
                })?;

                if args.len() != func.params.len() {
                    return Err(MizuError::ParseError(format!(
                        "function `{resolved_name}` expects {} argument(s), got {}",
                        func.params.len(),
                        args.len()
                    )));
                }

                let mut evaluated_args = Vec::with_capacity(args.len());
                for &arg_id in args {
                    evaluated_args.push(self.evaluate(
                        &arena[arg_id],
                        frame_pointer,
                        functions,
                        interner,
                        arena,
                    )?);
                }

                let new_fp = self.local_stack.len();
                for ((param_sym, expected_type), arg_val) in func.params.iter().zip(evaluated_args)
                {
                    let param_name = interner.resolve(*param_sym).unwrap_or("<unknown>");
                    check_type(&arg_val, expected_type, resolved_name, param_name)?;
                    self.push_local(*param_sym, arg_val);
                }

                let res = self.evaluate(
                    func.body.root(),
                    new_fp,
                    functions,
                    interner,
                    &func.body.arena,
                );
                self.truncate_locals(new_fp);
                res
            }
            Expr::Let {
                name: sym,
                value,
                body,
            } => {
                let bound_val =
                    self.evaluate(&arena[*value], frame_pointer, functions, interner, arena)?;
                self.push_local(*sym, bound_val);
                let res = self.evaluate(&arena[*body], frame_pointer, functions, interner, arena);
                self.pop_local();
                res
            }
            Expr::Not(inner) => {
                let val =
                    self.evaluate(&arena[*inner], frame_pointer, functions, interner, arena)?;
                match val {
                    Value::Bool(b) => Ok(Value::Bool(!b)),
                    other => Err(crate::core::errors::MizuError::TypeError {
                        expected: Box::new("bool".to_string()),
                        found: type_name(&other),
                    }),
                }
            }
            // Lazy: only the selected branch is evaluated.
            Expr::IfElse {
                condition,
                then_expr,
                else_expr,
            } => {
                let cond_val = self.evaluate(
                    &arena[*condition],
                    frame_pointer,
                    functions,
                    interner,
                    arena,
                )?;
                match cond_val {
                    Value::Bool(true) => self.evaluate(
                        &arena[*then_expr],
                        frame_pointer,
                        functions,
                        interner,
                        arena,
                    ),
                    Value::Bool(false) => self.evaluate(
                        &arena[*else_expr],
                        frame_pointer,
                        functions,
                        interner,
                        arena,
                    ),
                    other => Err(crate::core::errors::MizuError::TypeError {
                        expected: Box::new("bool".to_string()),
                        found: type_name(&other),
                    }),
                }
            }
            Expr::FieldAccess {
                base,
                field,
                field_hash,
            } => {
                let base_val =
                    self.evaluate(&arena[*base], frame_pointer, functions, interner, arena)?;
                if !matches!(base_val, Value::Record(_)) {
                    return Err(MizuError::TypeError {
                        expected: Box::new("record".to_string()),
                        found: type_name(&base_val),
                    });
                }
                let field_str = interner.resolve(*field).unwrap_or("");
                base_val
                    .get_field(*field_hash, field_str)
                    .cloned()
                    .ok_or_else(|| MizuError::VariableNotFound(field_str.to_string()))
            }
        }
    }
}

/// The error every over-budget interpolation write turns into.
///
/// A free function rather than an inline closure so all six write sites report
/// the limit identically, and so the `std::fmt::Error` — which carries no
/// information of its own — is never surfaced to a caller as if it were an
/// ordinary formatting failure.
fn interpolation_overflow(_: std::fmt::Error) -> MizuError {
    MizuError::SecurityViolation(format!(
        "interpolated text exceeds the {MAX_INTERPOLATED_BYTES}-byte render budget"
    ))
}

/// A `&mut String` that refuses writes past `cap` instead of growing.
///
/// The refusal happens *before* the bytes are copied, which is the point: the
/// values being formatted here are attacker-sized (a network response is
/// bounded only by the 32 MiB transfer cap), and a check applied after the
/// write would still pay the full copy — once per text node, on every layout
/// pass. Implementing [`std::fmt::Write`] rather than special-casing
/// [`Value`]'s shape means the bound holds for every `Display` impl, including
/// `List`/`Record` payloads that reach the buffer through many small writes.
struct CappedBuffer<'a> {
    buf: &'a mut String,
    cap: usize,
}

impl CappedBuffer<'_> {
    /// Remaining capacity, saturating rather than wrapping if the buffer was
    /// handed in already over budget.
    #[inline]
    fn remaining(&self) -> usize {
        self.cap.saturating_sub(self.buf.len())
    }

    fn push_str(&mut self, s: &str) -> Result<(), MizuError> {
        if s.len() > self.remaining() {
            return Err(interpolation_overflow(std::fmt::Error));
        }
        self.buf.push_str(s);
        Ok(())
    }

    fn push(&mut self, c: char) -> Result<(), MizuError> {
        if c.len_utf8() > self.remaining() {
            return Err(interpolation_overflow(std::fmt::Error));
        }
        self.buf.push(c);
        Ok(())
    }
}

impl std::fmt::Write for CappedBuffer<'_> {
    fn write_str(&mut self, s: &str) -> std::fmt::Result {
        if s.len() > self.remaining() {
            return Err(std::fmt::Error);
        }
        self.buf.push_str(s);
        Ok(())
    }
}

/// Returns the value of `field` in `item` if `item` is a `Record`.
///
/// Test-only. It hashes `field` on every call, so the production callers that
/// look one field up across a whole list — `sort`, `count`, `filter` — hoist
/// [`crate::core::types::hash_field`] out of their loop and call
/// [`Value::get_field`] directly instead of going through this.
#[cfg(test)]
pub(super) fn field_value<'a>(item: &'a Value, field: &str) -> Option<&'a Value> {
    item.get_field(crate::core::types::hash_field(field), field)
}

/// Navigates a dot-separated path through nested `Value::Record` values,
/// returning a reference to the leaf.
fn resolve_dot_path<'a, I>(root: &'a Value, segments: I) -> Option<&'a Value>
where
    I: IntoIterator,
    I::Item: AsRef<str>,
{
    let mut current = root;
    for segment in segments {
        current = current.get_field(
            crate::core::types::hash_field(segment.as_ref()),
            segment.as_ref(),
        )?;
    }
    Some(current)
}

/// Returns a stable numeric weight for each `Value` variant.
///
/// This weight is the tiebreaker used by [`compare_values`] when the two
/// values belong to different variants.  The ordering is arbitrary but fixed,
/// which is sufficient to satisfy Strict Weak Ordering.
///
/// Weights: Null=1, Bool=2, numeric=3, String=4, List=5, Record=6,
/// FileHandle=7.
///
/// `Int` and `Decimal` deliberately share a weight: they are one surface type
/// (`num`), so a heterogeneous pair of them must not be ordered by variant.
/// [`compare_values`] handles every such pair numerically before reaching
/// here, so the shared weight is never actually the deciding factor.
#[inline]
pub(super) fn variant_weight(v: &Value) -> u8 {
    match v {
        Value::Null => 1,
        Value::Bool(_) => 2,
        Value::Int(_) => 3,
        Value::Decimal(_) => 3,
        Value::String(_) => 4,
        Value::List(_) => 5,
        Value::Record(_) => 6,
        // Not meaningfully orderable — see `Value::PartialEq`'s doc comment;
        // this only needs a stable position for `sort`'s heterogeneous-pair
        // tiebreaker, never a real ordering between two file selections.
        Value::FileHandle(_) => 7,
    }
}

/// Compares two optional record-field values for sorting purposes, satisfying
/// Strict Weak Ordering so that `Vec::sort_by` never invokes undefined behaviour.
///
/// Rules:
/// * `(None, None)` → `Equal`
/// * `(None, Some(_))` → `Less` / `(Some(_), None)` → `Greater`  (None is smallest)
/// * Same-variant pairs use native ordering.
/// * All other heterogeneous pairs are ordered by [`variant_weight`], which is
///   deterministic and total.
///
/// A single call here costs O(string length) for a `String` pair, or more for
/// nested `List`/`Record` pairs — not O(1) like the numeric/bool cases. This
/// is safe *without* its own instruction charge because `sort`'s caller
/// already pre-charges `n·log₂n` for the whole pass (bounding the *count* of
/// calls), and every `Value` reachable here is itself already
/// budget-bounded: a `String`/`List`/`Record` built by the evaluator can only
/// be as large as the instructions already spent constructing it (string
/// concatenation charges its length — see `apply_binop`; there is no runtime
/// operator that grows a `List`/`Record`, so their size is fixed at parse
/// time), and values delivered by a network response are bounded separately
/// at the network layer, not by this instruction budget at all.
pub(super) fn compare_values(a: Option<&Value>, b: Option<&Value>) -> std::cmp::Ordering {
    use std::cmp::Ordering;
    match (a, b) {
        (None, None) => Ordering::Equal,
        (None, Some(_)) => Ordering::Less,
        (Some(_), None) => Ordering::Greater,

        (Some(Value::Null), Some(Value::Null)) => Ordering::Equal,
        (Some(Value::Bool(x)), Some(Value::Bool(y))) => x.cmp(y),

        // Numerics compare across the `Int`/`Decimal` split, in `i128` so the
        // upscale cannot overflow. Without the mixed arms these pairs would
        // fall through to `variant_weight`, which assigns both variants the
        // same weight — every comparison would answer `Equal` and `sort`
        // would silently leave a list of numbers in its original order.
        (Some(Value::Int(x)), Some(Value::Int(y))) => x.cmp(y),
        (Some(Value::Decimal(x)), Some(Value::Decimal(y))) => x.cmp(y),
        (Some(Value::Int(x)), Some(Value::Decimal(y))) => {
            (*x as i128 * super::value::DECIMAL_SCALE as i128).cmp(&(*y as i128))
        }
        (Some(Value::Decimal(x)), Some(Value::Int(y))) => {
            (*x as i128).cmp(&(*y as i128 * super::value::DECIMAL_SCALE as i128))
        }

        (Some(Value::String(x)), Some(Value::String(y))) => x.cmp(y),

        (Some(Value::List(x)), Some(Value::List(y))) => {
            for (elem_a, elem_b) in x.iter().zip(y.iter()) {
                let ord = compare_values(Some(elem_a), Some(elem_b));
                if ord != Ordering::Equal {
                    return ord;
                }
            }
            x.len().cmp(&y.len())
        }

        (Some(Value::Record(x)), Some(Value::Record(y))) => {
            for (fa, fb) in x.iter().zip(y.iter()) {
                let key_ord = fa.key.cmp(&fb.key);
                if key_ord != Ordering::Equal {
                    return key_ord;
                }
                let val_ord = compare_values(Some(&fa.value), Some(&fb.value));
                if val_ord != Ordering::Equal {
                    return val_ord;
                }
            }
            x.len().cmp(&y.len())
        }

        (Some(x), Some(y)) => variant_weight(x).cmp(&variant_weight(y)),
    }
}
